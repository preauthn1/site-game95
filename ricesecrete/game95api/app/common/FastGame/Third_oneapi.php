    public function setrdConstruct($apicfgs,$setrd_datas){
        $hitcfg=null;
        $s_arr = explode( 'wallet/', $setrd_datas['param']['s']);
        $method = $s_arr[1];
        //根据 $setrd_datas 内容获取真实的tc_id并获取配置
        switch ($method){
            case 'balance':
                $tcid=ThirdConfigs::where('tc_set_code',$apicfgs['trdcfg']['tc_set_code'])->where('tc_status',1)->field('tc_id')->find();
                if ($tcid){
                    $this->tcid = $tcid->tc_id;
                    $hitcfg=Games::getConfigs(null,$tcid->tc_id);
                }
                break;
            case 'bet':
            case 'bet_result':
            case 'rollback':
            case 'adjustment':
                $gid = $this->getGameIdByGameCode($setrd_datas['param']['gameCode']);
                if ($gid){
                    $hitcfg=Games::getConfigs($gid);
                    $this->tcid = $hitcfg['g_tcid'];
                }
                break;
        }
        //结束
        parent::setrdConstruct($hitcfg,$setrd_datas); // TODO: Change the autogenerated stub
    }

