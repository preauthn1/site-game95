    function transResultData($func, &$kds, $datas, $tcid, $uid, $gid, $ohterkvs)
    {
        $config = $this->apicfgs;
        if($func == 'GETUSERURL'){
            $name = Meta::initGetField('uname', $config['g_tcid'], $config['g_id'], $uid);
            $guser = UserThirds::where('ut_tcid',$tcid)->where('ut_uid',$uid)->find();
            if (!$guser){
                //TODO 错误处理
                UserThirds::create([
                    'ut_uid' => $uid,
                    'ut_tcid' => $tcid,
                    'ut_trdid' => $name,
                    'ut_intime' => time(),
                    'ut_token' => $datas['data']['token'],
                    'ut_state' => 0
                ]);
            }else{
                $guser->ut_trdid =  $name;
                $guser->ut_token =  $datas['data']['token'];
                //TODO 错误处理
                $guser->save();
            }
        }

        if($func == 'GETBETDETAIL') {
            $url = $config['trdcfg']['tc_api_urlpre'].'/transaction/detail';
            $params = json_encode([
                'traceId' => $this->generateUUID(),
                'betId' => $ohterkvs['gbsn']
            ]);
            $header = [
                'Content-Type: application/json',
                'X-API-Key: ' . $config['trdcfg']['tc_api_prikey'],
                'X-Signature: ' . $this->createSignature($config['trdcfg']['tc_api_signkey'], $params),
            ];
            // 增加HTTP代理请求
            $isProxy = env('IS_REQUIRE_GAME_PROXY', '');
            $proxy = '';
            if ($isProxy) {
                $proxy = env('GAME_PROXY_URL', '');
            }
            $res = json_decode(GameRequest::curl_post($url, $params, $header, $proxy), true);
            if( isset($res['data']['detailUrl']) ){
                $kds['tcgamedetailurl'] = $res['data']['detailUrl'];
            }
        }
    }

    //根据gameCode获取游戏id
    public function getGameIdByGameCode($gameCode = ''){
        if( !$gameCode ){
            return 0;
        }
        $thirdName = strtoupper(explode('_', $gameCode)[0]);
        $tCode = explode('_', $gameCode)[1];
        //获取平台id
        $tcId = ThirdConfigs::where('tc_code', '=', $thirdName.'ONEAPI')->value('tc_id');
        $gid = Game::getGamesInfoBy($tcId, $thirdName.'_'.$tCode, 'code', 'g_id');
        return $gid;
    }

    public function createSignature($apiSecret, $params){
        if( is_array($params) ){
            $params = json_encode($params);
        }
        return hash_hmac("sha256", $params, $apiSecret);
    }

    public function generateUUID($minLetter = 2, $maxLetter = 10) {
        //格式：xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx  32位
        $letterNum = rand($minLetter, $maxLetter);
        //生成字母
        $characters = 'abcdef';
        $letterArr = [];
        for ($i = 0; $i < $letterNum; $i++) {
            $letterArr[] = $characters[rand(0, strlen($characters) - 1)];
        }
        //生成数字
        $characters = '0123456789';
        $number = [];
        for ($i = 0; $i < 32 - count($letterArr); $i++) {
            $number[] = $characters[rand(0, strlen($characters) - 1)];
        }
        $arr = array_merge($number, $letterArr);
        shuffle($arr);#随机打乱
        $str = implode('', $arr);
        return substr($str, 0, 8) . '-' . substr($str, 8, 4) .
            '-' . substr($str, 12, 4) . '-' . substr($str, 16, 4) .
            '-' . substr($str, -12, 12);
    }

